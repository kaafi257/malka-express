const DICTS = { en, am, om } as const;
export type ReportKey = Key;

/** Translator for the report screens. Kept separate so the main dictionaries stay untouched. */
export function useRt(): (key: Key) => string {
  const { lang } = useI18n();
  return (key) => DICTS[lang][key] ?? en[key];
}

export function isEventKey(event: string): boolean {
  return `event.${event}` in en;
}
